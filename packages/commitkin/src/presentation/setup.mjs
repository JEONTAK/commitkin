// Reviewed immutable renderer with explicit, append-only first connection.
export const PROFILE_SYNC_REF = '6539f0219ff5e49de831025b1432984318853808';
const LOGIN = /^[a-z0-9](?:[a-z0-9-]{0,37}[a-z0-9])?$/i;

function sourceOwner(sourceRepository) {
  if (typeof sourceRepository !== 'string') throw new TypeError('SETUP_REPOSITORY_INVALID');
  const [owner, name, extra] = sourceRepository.split('/');
  if (!LOGIN.test(owner ?? '') || !/^[a-z0-9_.-]{1,100}$/i.test(name ?? '') || ['.', '..'].includes(name) || extra !== undefined || owner.toLowerCase() === name.toLowerCase()) throw new TypeError('SETUP_REPOSITORY_INVALID');
  return owner;
}

/** Fully personalized, manual-only workflow. No remote source code is executed from the fork. */
export function profileConnectionWorkflow(sourceRepository) {
  sourceOwner(sourceRepository);
  return `# Generated by Commitkin. Commit this file in your profile repository once.
name: Commitkin profile

"on":
  workflow_dispatch:
    inputs:
      mode:
        description: Preview changes or publish the saved character
        type: choice
        options: [preview, publish]
        default: preview
      connect_if_missing:
        description: First connection only; append a missing block without replacing existing content
        type: boolean
        default: false

permissions:
  contents: read

concurrency:
  group: commitkin-profile-display
  cancel-in-progress: false

jobs:
  preview:
    if: \${{ inputs.mode == 'preview' }}
    runs-on: ubuntu-24.04
    timeout-minutes: 5
    permissions:
      contents: read
    steps:
      - uses: JEONTAK/commitkin/profile-sync@${PROFILE_SYNC_REF}
        with:
          source-repository: '${sourceRepository}'
          initialize-if-missing: \${{ inputs.connect_if_missing }}
          dry-run: 'true'
  publish:
    if: \${{ inputs.mode == 'publish' }}
    runs-on: ubuntu-24.04
    timeout-minutes: 5
    permissions:
      contents: write
    steps:
      - uses: JEONTAK/commitkin/profile-sync@${PROFILE_SYNC_REF}
        with:
          source-repository: '${sourceRepository}'
          initialize-if-missing: \${{ inputs.connect_if_missing }}
          dry-run: 'false'
`;
}

/** Values are selected from validated context and known result fields, never remote Markdown. */
export function setupSummary({ sourceRepository, mode, report }) {
  const owner = sourceOwner(sourceRepository);
  const lines = ['# Commitkin setup', ''];
  const saved = report.published === true && report.publicationOutcome === 'published';
  const ready = (saved && report.progressionAuthorized === true) || report.decision === 'unchanged';
  if (saved && !ready) {
    lines.push('**Faction saved permanently. Analysis is pending.**', '',
      'XP and class are not finalized. Resolve the reported cause, then run **Set up Commitkin** in **save** mode with faction empty and the confirmation unchecked. Do not delete records or choose another faction.');
  } else if (ready) {
    lines.push(saved ? '**Character saved. Connect your profile next.**' : '**Saved character unchanged. You can connect your profile.**', '',
      `1. Open [${owner}/${owner}](https://github.com/${owner}/${owner}) (create this public profile repository with a README if needed).`,
      '2. Create `.github/workflows/commitkin-profile-sync.yml`, paste the code below and commit to its default branch.',
      '3. Open **Actions → Commitkin profile → Run workflow**. For the first connection, select **publish** and check **connect_if_missing**. Select **preview** first if you want a no-write check.', '',
      'Existing README content stays in place. Only a missing managed block is appended; malformed or duplicate markers stop safely. Future updates leave the checkbox unchecked.', '',
      '```yaml', profileConnectionWorkflow(sourceRepository).trimEnd(), '```');
  } else if (report.decision === 'prepared' && mode === 'preview') {
    lines.push('**Preview only. Nothing was saved or locked by this run.**', '',
      report.summary?.firstInstallation === false ?
        'Your saved faction stays permanent. To update, run **Set up Commitkin** with **save**, faction empty, and **confirm_faction** unchecked. For connection code without saving again, reopen a previous successful save Summary.' :
        'When ready, run **Set up Commitkin** again with **save**, the same faction, and **confirm_faction** checked. First save makes the faction permanent, including a pending reservation. The successful save summary will provide your personalized profile connection code.');
  } else if (report.decision === 'pending' && mode === 'preview') {
    lines.push('**Preview incomplete. Nothing was saved or locked.**', '',
      'Resolve the diagnostic cause before saving. A first save may reserve the faction permanently even while analysis is pending.');
  } else {
    lines.push('**Setup stopped. Do not delete or reset your records.**', '',
      report.actualRecordsChanged === null ? 'Publication outcome is unknown. Inspect the authoritative fork state before retrying.' :
        'Check the diagnostic code below. First save needs a faction and confirm_faction checked; after any saved snapshot, leave both empty/unchecked.');
  }
  const code = typeof report.code === 'string' && /^[A-Z][A-Z0-9_]{1,95}$/.test(report.code) ? report.code : 'SETUP_UNAVAILABLE';
  lines.push('', `Result: \`${code}\`.`, '',
    'Public activity only. Records stay in your fork; profile sync writes README only. No automatic runs, PAT or custom secret.');
  return lines.join('\n') + '\n';
}
